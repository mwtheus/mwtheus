// Ordem de prioridade: query (?lang=) > idioma do navegador > padrão (en)
function detectLang() {
  const q = (new URLSearchParams(location.search).get("lang") || "").toLowerCase();
  if (q.startsWith("pt")) return "pt";
  if (q.startsWith("en")) return "en";
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "";
  if (nav.toLowerCase().startsWith("pt")) return "pt";
  return "en";
}
let currentLang = detectLang();
function t(key) {
  const dict = I18N[currentLang] || I18N.en;
  if (dict[key] !== undefined) return dict[key];
  if (I18N.en[key] !== undefined) return I18N.en[key];
  return key;
}
function applyI18n() {
  document.documentElement.lang = currentLang === "pt" ? "pt-BR" : "en-US";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
  document.querySelectorAll("[data-i18n-alt]").forEach(el => {
    el.setAttribute("alt", t(el.getAttribute("data-i18n-alt")));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
  document.querySelectorAll("[data-lang-opt]").forEach(el => {
    el.classList.toggle("is-active", el.getAttribute("data-lang-opt") === currentLang);
  });
  if (typeof renderProjects === "function" && typeof PROJECTS !== "undefined") {
    renderProjects(PROJECTS);
  }
  if (typeof startTypewriter === "function") {
    startTypewriter();
  }
}
function setLang(lang) {
  currentLang = lang === "pt" ? "pt" : "en";
  applyI18n();
}
