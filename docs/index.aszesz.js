// Centraliza a aba ativa dentro da barra horizontal (que tem overflow-x: auto)
function centerActiveTab() {
  if (!tabsNav) return;
  const active = tabsNav.querySelector(".tab.is-active");
  if (!active) return;
  const navRect = tabsNav.getBoundingClientRect();
  const activeRect = active.getBoundingClientRect();
  const delta = (activeRect.left - navRect.left)
    - (tabsNav.clientWidth - activeRect.width) / 2;
  tabsNav.scrollTo({
    left: tabsNav.scrollLeft + delta,
    behavior: reduceMotion ? "auto" : "smooth"
  });
}
